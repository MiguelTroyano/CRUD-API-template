from fastapi import APIRouter, HTTPException, Depends, status
from sqlmodel import Session, select

from auth import get_current_user
from database import get_session
from models import User, Item
from schemas import ItemCreate, ItemRead, ItemUpdate

router = APIRouter(prefix="/items", tags=["items"])
# prefix: every route in this router hangs from /items,
# which is why "" is written below instead of "/items".
# tags: grouping in /docs

#Route /items: POST to create one, GET to fetch all of them (as a list of JSON objects)
@router.post("", response_model=ItemRead, status_code=status.HTTP_201_CREATED)        # same as writing status_code=201 (readability)
def create_item(data: ItemCreate,
                session: Session = Depends(get_session),
                user: User = Depends(get_current_user)):
    item = Item(
        title = data.title,
        user_id = user.id
        # id is generated by SQL, and done uses its default (False)
    )

    session.add(item)         #item in TRANSIENT state, the add method puts it in the DB (runs INSERT)
    session.commit()
    session.refresh(item)
    return item

"""
Specifying the 201 status code (and 204 for deletes) helps any person/program making requests to the API
understand what just happened.
"""

@router.get("", response_model=list[ItemRead])
def list_items(
    session: Session = Depends(get_session),
    user: User = Depends(get_current_user)
):
    return session.exec(select(Item).where(Item.user_id == user.id)).all()       # returns a list of items, which FastAPI automatically converts to JSON
"""
The line above could have been replaced with SQLModel's Relationship, which lets you list rows that share a
foreign key / primary key in a clearer and more concise way.
"""


#Get a single item: route /items/{id}. PUT to modify, DELETE to remove.

"""
In REST APIs, the PUT method is conventionally used to update a whole object, that is,
to put a new object where there used to be another one. Here we only change 1 attribute of the item,
so the PATCH method would be more correct. However, both methods work, and since PUT is more
versatile, we'll use PUT.
"""
@router.put("/{item_id}", response_model=ItemRead)
def update_item(item_id: int,
                data: ItemUpdate,
                session: Session = Depends(get_session),
                user: User = Depends(get_current_user)):
    """
    Modifies the specified fields of an item.
    """
    item = session.get(Item, item_id)         #.get(Table, id) is used to find a row by its primary key

    #Error handling, needed before modifying anything
    if not item or item.user_id != user.id:
        raise HTTPException(status_code=404, detail=f"Item with id {item_id} not found")      #"not found" is also raised if the item exists but belongs to another user.

    # PATCH behaviour: filter by the arguments that were sent (with PUT, all of them are sent)
    updates = data.model_dump(exclude_unset=True)        # turns the JSON into a dictionary, dropping the fields that weren't sent
    for field, value in updates.items():
        setattr(item, field, value)           # (we have the field name as a string, so setattr is the convenient way)

    session.commit()
    session.refresh(item)
    return item


@router.delete("/{item_id}", status_code=status.HTTP_204_NO_CONTENT)
def delete_item(item_id: int,
                session: Session = Depends(get_session),
                user: User = Depends(get_current_user)):
    item = session.get(Item, item_id)

    if not item or item.user_id != user.id:
        raise HTTPException(404, detail=f"Could not delete item with id {item_id} because it does not exist")

    session.delete(item)
    session.commit()

    return None         # a 204 has no body
